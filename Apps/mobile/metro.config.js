// Metro for the phone app. Besides this folder it reads the site's shared
// modules in ../../src/lib (client-safe ones only, like the browser extension)
// and the public background photos. Bare imports made from there (luxon,
// adhan…) resolve to this app's node_modules, never the repo root's.
// The aliases (@lib/…, @/…) are resolved here, not from tsconfig.json, whose
// `paths` also point luxon/adhan at their types for the typecheck
// (app.json turns Metro's tsconfig paths off).
const fs = require("node:fs");
const path = require("node:path");
const { getDefaultConfig } = require("expo/metro-config");

const projectRoot = __dirname;
const repoRoot = path.resolve(projectRoot, "../..");
const shared = [path.join(repoRoot, "src", "lib"), path.join(repoRoot, "public", "bg")];

/**
 * The data files the app bundles (src/shims/node-fs.ts requires each), written
 * into generated/data (gitignored) as one JSON string each, so data.ts parses
 * them once instead of the app building a 1.5 MB object and stringifying it.
 * Written again whenever Metro starts and a file changed.
 */
const DATA_FILES = ["hisn.json", "quran.json", "qcf.json", "reciters.json", "radios.json", "tafsir-muyassar.json"];
const generated = path.join(projectRoot, "generated", "data");
fs.mkdirSync(generated, { recursive: true });
for (const name of DATA_FILES) {
  const json = JSON.stringify(JSON.parse(fs.readFileSync(path.join(repoRoot, "data", name), "utf8")));
  const out = path.join(generated, name.replace(/\.json$/, ".js"));
  const body = `// Generated by metro.config.js from data/${name}: its JSON as one string (src/lib/content/data.ts parses it).\nmodule.exports = ${JSON.stringify(json)};\n`;
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);
}

/**
 * Small data files that src/lib imports as JSON (asma.ts): copied into
 * generated/json and resolved there, so Metro needn't watch the whole data/
 * folder (fonts, PDFs, the hadith books…).
 */
const JSON_IMPORTS = ["asma-husna.json"];
const generatedJson = path.join(projectRoot, "generated", "json");
fs.mkdirSync(generatedJson, { recursive: true });
for (const name of JSON_IMPORTS) {
  const body = fs.readFileSync(path.join(repoRoot, "data", name), "utf8");
  const out = path.join(generatedJson, name);
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);
}

/** src/lib/content/data.ts reads data/*.json with node:fs: in the app, the files bundled by src/shims. */
const NODE_SHIMS = {
  "node:fs": path.join(projectRoot, "src", "shims", "node-fs.ts"),
  "node:path": path.join(projectRoot, "src", "shims", "node-path.ts"),
};

const config = getDefaultConfig(projectRoot);
config.watchFolders = [...(config.watchFolders ?? []), ...shared];

const appOrigin = path.join(projectRoot, "package.json");
const isBare = (name) => !name.startsWith(".") && !path.isAbsolute(name);
const fromShared = (origin) => shared.some((dir) => origin.startsWith(dir + path.sep));

const ALIASES = [
  ["@lib/", path.join(repoRoot, "src", "lib") + path.sep],
  ["@/", path.join(projectRoot, "src") + path.sep],
];

const upstream = config.resolver.resolveRequest;
config.resolver.resolveRequest = (context, moduleName, platform) => {
  const resolve = upstream ?? context.resolveRequest;
  if (Object.hasOwn(NODE_SHIMS, moduleName)) return { type: "sourceFile", filePath: NODE_SHIMS[moduleName] };
  const json = /(?:^|\/)data\/([\w-]+\.json)$/.exec(moduleName);
  if (json && JSON_IMPORTS.includes(json[1]) && fromShared(context.originModulePath)) return { type: "sourceFile", filePath: path.join(generatedJson, json[1]) };
  const alias = ALIASES.find(([prefix]) => moduleName.startsWith(prefix));
  if (alias) return resolve(context, alias[1] + moduleName.slice(alias[0].length), platform);
  if (isBare(moduleName) && fromShared(context.originModulePath)) {
    return resolve({ ...context, originModulePath: appOrigin }, moduleName, platform);
  }
  return resolve(context, moduleName, platform);
};

module.exports = config;
