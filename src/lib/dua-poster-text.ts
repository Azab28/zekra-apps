/** A name on the poster: letters (any script), spaces and a few marks, at most 40 characters and 6 words. */
export function posterName(v: string): string {
  return v
    .normalize("NFC")
    .replace(/[^\p{L}\p{M} '.\-]/gu, "")
    .replace(/\s+/g, " ")
    .trim()
    .split(" ")
    .slice(0, 6)
    .join(" ")
    .slice(0, 40)
    .trim();
}
